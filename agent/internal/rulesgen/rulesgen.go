// Package rulesgen writes the input checks of the agent (Go) and the input rules of the panel
// API (PHP) from one file: schema/input-rules.json. Thus the panel and the agent always accept
// the same values (audit findings R5 and F04). The command cf-rules uses this package.
package rulesgen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

type rule struct {
	What      string   `json:"what"`
	Go        string   `json:"go"`
	Doc       string   `json:"doc"`
	Pattern   string   `json:"pattern"`
	Also      []string `json:"also"`
	Not       []string `json:"not"`
	MaxLength int      `json:"maxLength"`
	Empty     bool     `json:"empty"`
	Echo      *bool    `json:"echo"`
	Message   string   `json:"message"`
}

type set struct {
	Doc    string   `json:"doc"`
	Values []string `json:"values"`
}

type limit struct {
	Doc   string `json:"doc"`
	Value int    `json:"value"`
}

type schema struct {
	Comment   string            `json:"comment"`
	Fragments map[string]string `json:"fragments"`
	Rules     map[string]rule   `json:"rules"`
	Sets      map[string]set    `json:"sets"`
	Limits    map[string]limit  `json:"limits"`
}

const header = "Code generated by agent/cmd/cf-rules from schema/input-rules.json. DO NOT EDIT."

// Generate gives the Go file and the PHP file for the text of the rules file.
func Generate(rules []byte) (goCode, phpCode []byte, err error) {
	s, err := load(rules)
	if err != nil {
		return nil, nil, err
	}
	if goCode, err = goFile(s); err != nil {
		return nil, nil, err
	}
	return goCode, phpFile(s), nil
}

var fragment = regexp.MustCompile(`\{([A-Za-z]+)\}`)

// load reads the rules file, puts the fragments in the patterns and checks each rule.
func load(b []byte) (*schema, error) {
	var s schema
	dec := json.NewDecoder(bytes.NewReader(b))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&s); err != nil {
		return nil, err
	}
	expand := func(p string) (string, error) {
		var missing string
		out := fragment.ReplaceAllStringFunc(p, func(m string) string {
			f, ok := s.Fragments[m[1:len(m)-1]]
			if !ok {
				missing = m
			}
			return f
		})
		if missing != "" {
			return "", fmt.Errorf("the fragment %s does not exist", missing)
		}
		// The two languages must read the pattern in the same way: RE2 syntax, which PCRE also
		// reads. regexp.Compile refuses the PCRE syntax that RE2 does not have.
		if _, err := regexp.Compile(out); err != nil {
			return "", err
		}
		return out, nil
	}
	for name, r := range s.Rules {
		if r.What == "" || r.Doc == "" || r.Message == "" || r.Pattern == "" {
			return nil, fmt.Errorf("the rule %q must have: what, doc, pattern and message", name)
		}
		if !strings.HasPrefix(r.Pattern, "^") || !strings.HasSuffix(r.Pattern, "$") {
			return nil, fmt.Errorf("the pattern of the rule %q must start with ^ and end with $", name)
		}
		var err error
		if r.Pattern, err = expand(r.Pattern); err != nil {
			return nil, fmt.Errorf("the rule %q: %w", name, err)
		}
		for _, list := range [][]string{r.Also, r.Not} {
			for i := range list {
				if list[i], err = expand(list[i]); err != nil {
					return nil, fmt.Errorf("the rule %q: %w", name, err)
				}
			}
		}
		s.Rules[name] = r
	}
	return &s, nil
}

func keys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// goName gives "UnixUser" for "unixUser".
func goName(key string, r rule) string {
	if r.Go != "" {
		return r.Go
	}
	return strings.ToUpper(key[:1]) + key[1:]
}

// phpName gives "UNIX_USER" for "unixUser" and "SHA256" for "sha256".
func phpName(key string) string {
	var b strings.Builder
	for i, c := range key {
		if unicode.IsUpper(c) && i > 0 {
			b.WriteByte('_')
		}
		b.WriteRune(unicode.ToUpper(c))
	}
	return b.String()
}

// goRegexp gives a Go string for a pattern. A raw string is easier to read.
func goRegexp(p string) string {
	if strings.Contains(p, "`") {
		return strconv.Quote(p)
	}
	return "`" + p + "`"
}

func goFile(s *schema) ([]byte, error) {
	var b bytes.Buffer
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("// %s\n\npackage validate\n\nimport \"regexp\"\n\n", header)

	for _, key := range keys(s.Rules) {
		r := s.Rules[key]
		name := goName(key, r)
		w("var rule%s = rule{\n", name)
		w("what: %q,\n", r.What)
		w("pattern: regexp.MustCompile(%s),\n", goRegexp(r.Pattern))
		list := func(field string, patterns []string) {
			if len(patterns) == 0 {
				return
			}
			w("%s: []*regexp.Regexp{", field)
			for _, p := range patterns {
				w("regexp.MustCompile(%s),", goRegexp(p))
			}
			w("},\n")
		}
		list("also", r.Also)
		list("not", r.Not)
		if r.MaxLength > 0 {
			w("maxLength: %d,\n", r.MaxLength)
		}
		if r.Empty {
			w("empty: true,\n")
		}
		if r.Echo == nil || *r.Echo {
			w("echo: true,\n")
		}
		w("}\n\n")
		w("// %s checks a value with the rule %q of schema/input-rules.json.\n//\n// %s\n", name, key, r.Doc)
		w("func %s(s string) error { return rule%s.check(s) }\n\n", name, name)
	}

	w("// rules has each rule by its name in schema/input-rules.json.\nvar rules = map[string]*rule{\n")
	for _, key := range keys(s.Rules) {
		w("%q: &rule%s,\n", key, goName(key, s.Rules[key]))
	}
	w("}\n\n")

	for _, key := range keys(s.Sets) {
		w("// %s\nvar %s = []string{", s.Sets[key].Doc, key)
		for _, v := range s.Sets[key].Values {
			w("%q,", v)
		}
		w("}\n\n")
	}
	for _, key := range keys(s.Limits) {
		w("// Max%s: %s\nconst Max%s = %d\n\n", goName(key, rule{}), s.Limits[key].Doc, goName(key, rule{}), s.Limits[key].Value)
	}
	return format.Source(b.Bytes())
}

// pcre gives one PCRE pattern for a rule. The modifier D makes "$" match only at the end of
// the text, as in Go. Without it, PCRE also accepts a value with a line feed at the end.
func pcre(r rule) string {
	var b strings.Builder
	if r.MaxLength > 0 {
		fmt.Fprintf(&b, `(?=[\s\S]{0,%d}\z)`, r.MaxLength)
	}
	for _, p := range r.Also {
		fmt.Fprintf(&b, `(?=[\s\S]*?(?:%s))`, p)
	}
	for _, p := range r.Not {
		fmt.Fprintf(&b, `(?![\s\S]*?(?:%s))`, p)
	}
	fmt.Fprintf(&b, `(?:%s)`, r.Pattern)
	body := b.String()
	if r.Empty {
		body = `(?:\z|` + body + `)`
	}
	return "/^" + strings.ReplaceAll(body, "/", `\/`) + "/D"
}

// phpString gives a PHP string in single quotes.
func phpString(s string) string {
	return "'" + strings.NewReplacer(`\`, `\\`, `'`, `\'`).Replace(s) + "'"
}

func phpFile(s *schema) []byte {
	var b bytes.Buffer
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("<?php\n\n// %s\n\nnamespace App\\Validation;\n\n", header)
	w("/**\n * The input rules that the panel and the agent share. Use App\\Validation\\Input to apply a rule.\n */\nfinal class InputRules\n{\n")
	for _, key := range keys(s.Rules) {
		w("    /** %s */\n    public const %s = %s;\n\n", s.Rules[key].Doc, phpName(key), phpString(pcre(s.Rules[key])))
	}
	w("    /** Each pattern by the name of its rule in schema/input-rules.json. */\n    public const PATTERNS = [\n")
	for _, key := range keys(s.Rules) {
		w("        %s => self::%s,\n", phpString(key), phpName(key))
	}
	w("    ];\n\n    /** The text that tells a person how to correct a value. */\n    public const MESSAGES = [\n")
	for _, key := range keys(s.Rules) {
		w("        %s => %s,\n", phpString(key), phpString(s.Rules[key].Message))
	}
	w("    ];\n")
	for _, key := range keys(s.Sets) {
		quoted := make([]string, len(s.Sets[key].Values))
		for i, v := range s.Sets[key].Values {
			quoted[i] = phpString(v)
		}
		w("\n    /** %s */\n    public const %s = [%s];\n", s.Sets[key].Doc, phpName(key), strings.Join(quoted, ", "))
	}
	for _, key := range keys(s.Limits) {
		w("\n    /** %s */\n    public const MAX_%s = %d;\n", s.Limits[key].Doc, phpName(key), s.Limits[key].Value)
	}
	w("}\n")
	return b.Bytes()
}
